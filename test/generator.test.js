import assert from "node:assert/strict";
import test from "node:test";

import { IGNORE_BLOCKS } from "../public/js/blocks.js";
import {
  generateIgnoreFile,
  normalizePatternIds,
} from "../public/js/generator.js";

const TEST_BLOCKS = [
  {
    id: "alpha",
    name: "Alpha",
    title: "//---Alpha---//",
    patterns: "alpha-cache\nalpha-temp",
  },
  {
    id: "beta",
    name: "Beta",
    title: "//---Beta---//",
    patterns: "beta-cache",
  },
];

test("test_catalog_is_valid", () => {
  assert.ok(Array.isArray(IGNORE_BLOCKS));
  assert.notEqual(IGNORE_BLOCKS.length, 0);
  const ids = new Set();

  for (const [blockIndex, block] of IGNORE_BLOCKS.entries()) {
    assert.equal(
      typeof block,
      "object",
      `Block ${blockIndex} must be an object.`,
    );
    assert.match(block.id, /^[a-z0-9]+(?:-[a-z0-9]+)*$/);
    assert.equal(ids.has(block.id), false, `Duplicate block ID: ${block.id}`);
    assert.equal(block.id, block.id.trim());
    assert.equal(typeof block.name, "string");
    assert.notEqual(block.name.trim(), "");
    assert.equal(block.name, block.name.trim());
    assert.equal(typeof block.title, "string");
    assert.ok(block.title.startsWith("//"));
    assert.equal(block.title, block.title.trim());
    assert.equal(typeof block.patterns, "string");
    assert.notEqual(block.patterns, "");
    assert.equal(block.patterns.includes("\r"), false);
    assert.equal(block.patterns, block.patterns.trimEnd());
    for (const line of block.patterns.split("\n")) {
      assert.equal(
        line,
        line.trimEnd(),
        `Trailing whitespace in block: ${block.id}`,
      );
    }
    ids.add(block.id);
  }
});

test("test_normalize_pattern_ids_preserves_order_and_removes_duplicates", () => {
  assert.deepEqual(normalizePatternIds(" Unity, WINDOWS,unity, ,macos "), [
    "unity",
    "windows",
    "macos",
  ]);
  assert.deepEqual(normalizePatternIds(["linux", null, "LINUX", "macos"]), [
    "linux",
    "macos",
  ]);
  assert.deepEqual(normalizePatternIds(undefined), []);
});

test("test_generate_single_block_with_final_lf", () => {
  const sourceUrl = "https://stignore.example/api?patterns=alpha";
  const result = generateIgnoreFile("alpha", sourceUrl, TEST_BLOCKS);

  assert.deepEqual(result.selectedIds, ["alpha"]);
  assert.deepEqual(result.unknownIds, []);
  assert.equal(
    result.text,
    `// generated by: ${sourceUrl}\n\n` +
      `${TEST_BLOCKS[0].title}\n${TEST_BLOCKS[0].patterns}\n`,
  );
  assert.equal(result.text.endsWith("\n"), true);
  assert.equal(result.text.endsWith("\n\n"), false);
});

test("test_generate_multiple_blocks_preserves_request_order", () => {
  const result = generateIgnoreFile(
    "beta,alpha,beta",
    "https://stignore.example/api?patterns=beta,alpha,beta",
    TEST_BLOCKS,
  );
  const betaIndex = result.text.indexOf(TEST_BLOCKS[1].title);
  const alphaIndex = result.text.indexOf(TEST_BLOCKS[0].title);

  assert.deepEqual(result.selectedIds, ["beta", "alpha"]);
  assert.ok(betaIndex >= 0 && alphaIndex > betaIndex);
});

test("test_generate_skips_unknown_ids_with_warning", () => {
  const sourceUrl =
    "https://stignore.example/api?patterns=missing,alpha,other";
  const result = generateIgnoreFile(
    "missing,alpha,other",
    sourceUrl,
    TEST_BLOCKS,
  );

  assert.deepEqual(result.selectedIds, ["alpha"]);
  assert.deepEqual(result.unknownIds, ["missing", "other"]);
  assert.ok(
    result.text.startsWith(
      `// generated by: ${sourceUrl}\n\n` +
        "// WARNING: Unknown block IDs skipped: missing, other\n\n",
    ),
  );
  assert.ok(result.text.includes(TEST_BLOCKS[0].title));
});

test("test_generate_empty_input_returns_empty_text", () => {
  assert.deepEqual(
    generateIgnoreFile("", "https://stignore.example/api", TEST_BLOCKS),
    {
      text: "",
      requestedIds: [],
      selectedIds: [],
      unknownIds: [],
    },
  );
});
